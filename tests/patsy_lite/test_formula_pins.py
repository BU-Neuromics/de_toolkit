"""
Pins of the model matrices patsy-lite builds today (#71, DETK-0001).

Each case names a column data file under ``data/`` and a formula; its pin
under ``pins/<case>.csv`` holds the full model matrix as detk builds it
today: the column names and their order, the values, and the row order
(the index). The left- and right-hand side names are pinned here, beside
the formula. The pins are literal files written once from patsy-lite on
patsy (DETK-0001) and checked by hand; they are not regenerated by the
tests, so a formula library that builds a different matrix fails them.

Designs that use the special ``counts`` term are built the way detk builds
them, through CountMatrix, which adds a ``counts`` column of zeros to the
column data before the design is made.

Error cases are pinned by exception type and by the substance of the
message (what it names), not its exact wording.

The documented ``np.log(...)`` pass-through and plain ``a:b`` interactions
are pinned as they behave today, which is not as documented (see the
comments at those cases); this module records that, it does not fix it.
"""

from pathlib import Path
