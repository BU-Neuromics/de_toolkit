@pytest.mark.parametrize("case, data, formula, names", ERRORS, ids=[_[0] for _ in ERRORS])
def test_formula_error(case, data, formula, names):
    with pytest.raises(PatsyLiteParseError, match=names):
        DesignMatrix(formula, column_data(data))


def test_count_matrix_wraps_parse_errors():
    "CountMatrix reports a formula patsy-lite cannot build as an invalid design."
    cd = column_data("de_fake")
    counts = pandas.DataFrame(1.0, index=["g1"], columns=cd.index)
    with pytest.raises(InvalidDesignException, match=r"could not parse.*\bnope\b"):
        CountMatrix(counts, cd, "counts ~ nope")


def test_count_matrix_requires_counts():
    "A design without counts, where CountMatrix requires one."
    cd = column_data("de_fake")
    counts = pandas.DataFrame(1.0, index=["g1"], columns=cd.index)
    with pytest.raises(InvalidDesignException, match=r'"counts" must exist'):
        CountMatrix(counts, cd, "category ~ cont_cov")


