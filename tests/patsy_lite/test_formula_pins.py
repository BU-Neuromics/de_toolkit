from de_toolkit.patsy_lite import DesignMatrix, PatsyLiteParseError

HERE = Path(__file__).parent
DATA = HERE / "data"
PINS = HERE / "pins"
R_CHECK_NAMES_META = HERE.parent / "de" / "R_check_names_meta.csv"


def column_data(name):
    "The column data file *name*, read as detk reads a column data file."
    path = R_CHECK_NAMES_META if name == "R_check_names_meta" else DATA / f"{name}.csv"
    return read_id_table(str(path))


def build(data, formula):
    """
    The DesignMatrix detk builds for *formula* on the column data file
    *data*: through CountMatrix when the formula uses ``counts``, else
    directly.
    """
    cd = column_data(data)
    if "counts" in formula:
        counts = pandas.DataFrame(1.0, index=["g1", "g2"], columns=cd.index)
        return CountMatrix(counts, cd, formula).design_matrix
    return DesignMatrix(formula, cd)


