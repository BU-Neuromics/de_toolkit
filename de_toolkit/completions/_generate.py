"""
Generate the shipped shell completion scripts from the detk parsers with
shtab (DETK-0032). shtab is a dev dependency, not a runtime one: this module
imports it only when it runs, and nothing at run time imports this module.

    uv run python -m de_toolkit.completions._generate

rewrites ``de_toolkit/completions/detk.{bash,zsh,tcsh}``;
tests/completion/ fails when the shipped files differ from what this gives.
Each file holds the script of ``detk`` (its commands, each completing as the
module command it runs) and of every ``detk-<command>`` entry point.
"""

import argparse
import importlib
from pathlib import Path

from ..common import COMPLETION_SHELLS, MODULE_COMMANDS, build_parser

HERE = Path(__file__).parent

# the module of each entry point (pyproject [project.scripts]), in order
ENTRY_POINTS = {f"detk-{cmd}": cmd for cmd in MODULE_COMMANDS}

# positionals that name a file, besides those whose name ends in _fn
_FILE_POSITIONALS = {"rscript", "counts_in", "out", "files"}


def _subparsers(parser):
    for action in parser._actions:
        if isinstance(action, argparse._SubParsersAction):
            return action
    return None


def _mark_paths(parser, shtab):
    "Complete file and directory names where an argument takes one"
    for action in parser._actions:
        if action.choices is not None and not isinstance(action, argparse._SubParsersAction):
            continue
        if action.option_strings:
            if action.metavar == "FILE":
                action.complete = shtab.FILE
            elif action.metavar == "DIR":
                action.complete = shtab.DIRECTORY
        elif action.dest.endswith("_fn") or action.dest in _FILE_POSITIONALS:
            action.complete = shtab.FILE
    subs = _subparsers(parser)
    if subs is not None:
        for sub in subs.choices.values():
            _mark_paths(sub, shtab)


def module_parser(cmd):
    "The parser of ``detk-<cmd>``"
    return importlib.import_module(f"de_toolkit.{cmd}").build_parser()


def umbrella_parser():
    """
    The ``detk`` parser for completion: each module command's stub replaced
    by the module's own parser, so ``detk norm deseq2 -<TAB>`` completes as
    ``detk-norm deseq2 -<TAB>`` does
    """
    parser = build_parser()
    subs = _subparsers(parser)
    for cmd in MODULE_COMMANDS:
        sub = module_parser(cmd)
        sub.prog = f"detk {cmd}"
        subs.choices[cmd] = sub
    return parser


def parsers():
    "(prog, parser) for every detk command, ``detk`` first"
    yield "detk", umbrella_parser()
    for prog, cmd in ENTRY_POINTS.items():
        yield prog, module_parser(cmd)


def generate(shell):
    "The completion script of every detk command for *shell*, as text"
    import shtab

    scripts = []
    for prog, parser in parsers():
        parser.prog = prog
        _mark_paths(parser, shtab)
        # a prefix of its own for each script, so detk's "de" subcommand
        # (_shtab_detk_de...) and detk-de (_shtab_detk_cmd_de...) do not share
        # function names in one file
        prefix = "detk" if prog == "detk" else "detk_cmd_" + prog.removeprefix("detk-")
        script = shtab.complete(parser, shell=shell, root_prefix=prefix)
        scripts.append(_drop_usage_comment(script).strip("\n") + "\n")
    header = (
        f"# detk shell completion for {shell}: detk and every detk-<command>.\n"
        "# Generated by shtab (https://github.com/tqdm/shtab) from the detk parsers\n"
        "# with python -m de_toolkit.completions._generate; do not edit.\n"
        f"# Load it as `detk completion {shell} --help` says.\n"
    )
    return header + "\n".join(scripts)


def _drop_usage_comment(script):
    """
    shtab's comment on installing a script for one command (from its
    "AUTOMATICALLY GENERATED" line to "See also"), which does not fit a file
    holding the scripts of every detk command; the header says how to load it
    """
    out, skipping = [], False
    for line in script.splitlines():
        if line.startswith("# AUTOMATICALLY GENERATED"):
            skipping = True
        if not skipping:
            out.append(line)
        if skipping and line.startswith("# See also"):
            skipping = False
    return "\n".join(out)


def main():
    for shell in COMPLETION_SHELLS:
        path = HERE / f"detk.{shell}"
        path.write_text(generate(shell))
        print(f"wrote {path}")


if __name__ == "__main__":
    main()
