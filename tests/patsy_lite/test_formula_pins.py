def read_pin(case):
    "The pinned full model matrix for *case*."
    pin = pandas.read_csv(PINS / f"{case}.csv", index_col=0, dtype={0: str})
    return pin.astype("float64")


@pytest.mark.parametrize("case, data, formula, lhs, rhs", CASES, ids=[_[0] for _ in CASES])
def test_formula_pin(case, data, formula, lhs, rhs):
    dm = build(data, formula)

    assert list(dm.lhs.columns) == lhs
    assert list(dm.rhs.columns) == rhs
    assert dm.design == f"{' + '.join(lhs)} ~ {' + '.join(rhs)}"

    full = dm.full_matrix
    # every column of the matrix is float64
    assert all(dtype == numpy.float64 for dtype in full.dtypes)
    # rows come in the column data file's order, named by its first column
    assert list(full.index) == list(column_data(data).index)

    pandas.testing.assert_frame_equal(
        full, read_pin(case), check_exact=True, check_names=False, check_index_type=False
    )


def test_every_pin_has_a_case():
    "No pin file is left without a case, and no case without a pin."
    assert sorted(_.stem for _ in PINS.glob("*.csv")) == sorted(_[0] for _ in CASES)


